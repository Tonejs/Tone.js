import path from "node:path";

import * as esbuild from "esbuild";

/**
 * Bundles a single `*.worklet.ts` entry point (which runs in the
 * AudioWorkletGlobalScope, not the DOM) together with its dependencies into a
 * self-contained IIFE, then wraps it as `export const audioWorklet = \`...\`;`.
 * No plugins are passed to this nested build, so it can never recurse into
 * itself even if called from within an esbuild plugin.
 */
export async function bundleWorkletToModule(entryPath) {
	const result = await esbuild.build({
		entryPoints: [entryPath],
		bundle: true,
		write: false,
		format: "iife",
		target: "es2020",
		platform: "browser",
		minify: true,
	});

	const code = result.outputFiles[0].text.trim();

	// escape the bundled code so it can be safely embedded in a template literal
	const escaped = code
		.replace(/\\/g, "\\\\")
		.replace(/`/g, "\\`")
		.replace(/\$\{/g, "\\${");

	const banner =
		"// This file is auto-generated by `npm run build:worklets`. Do not edit directly.\n";
	return `${banner}export const audioWorklet = \`\n${escaped}\n\`;\n`;
}

/**
 * Intercepts imports ending in `.worklet.code.js` (e.g. "./BitCrusher.worklet.code.js")
 * and resolves the path to its real sibling `*.worklet.ts` implementation, bundling
 * it in-memory instead of loading it from disk. Lets a single esbuild bundle pass
 * (e.g. the single-file build) inline worklet code directly, without needing the
 * generated files to exist on disk first.
 */
export function workletInlinePlugin() {
	return {
		name: "worklet-inline",
		setup(build) {
			build.onResolve(
				{ filter: /\.worklet\.code\.js$/ },
				async (args) => {
					const specifier = args.path.replace(
						/\.worklet\.code\.js$/,
						".worklet.ts"
					);
					const resolved = await build.resolve(specifier, {
						kind: args.kind,
						resolveDir: path.dirname(args.importer),
					});
					if (resolved.errors.length > 0) {
						return { errors: resolved.errors };
					}
					return { path: resolved.path, namespace: "worklet-inline" };
				}
			);

			// namespaced so this never matches a normal file load, and the nested
			// build in bundleWorkletToModule has no plugins so it can't recurse here
			build.onLoad(
				{ filter: /.*/, namespace: "worklet-inline" },
				async (args) => ({
					contents: await bundleWorkletToModule(args.path),
					loader: "js",
				})
			);
		},
	};
}
